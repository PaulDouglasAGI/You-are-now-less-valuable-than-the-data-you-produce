export const QUIZ_PASS_THRESHOLD = 0.7;
export const QUIZ_SESSION_SIZE = 10;

export function quizCellKey(tier: QuizTier, category: QuizCategory | "all") {
  return `${tier}:${category}`;
}

/** all questions for a tier, optionally narrowed to one category ("all" = every category mixed) */
export function questionsFor(tier: QuizTier, category: QuizCategory | "all"): QuizQuestion[] {
  return QUIZ_QUESTIONS.filter((q) => q.tier === tier && (category === "all" || q.category === category));
}

function shuffle<T>(arr: T[]): T[] {
  const out = [...arr];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/** a random session of up to QUIZ_SESSION_SIZE questions, shuffled — uses the whole pool if smaller */
export function buildQuizSession(tier: QuizTier, category: QuizCategory | "all"): QuizQuestion[] {
  return shuffle(questionsFor(tier, category)).slice(0, QUIZ_SESSION_SIZE);
}

/** folds a completed session's result into QuizProgress: keeps the best score per cell, and adds
 *  the tier to clearedTiers the first time its "all categories" mixed quiz is passed at >=70%. */
export function recordQuizResult(
  progress: QuizProgress,
  tier: QuizTier,
  category: QuizCategory | "all",
  correct: number,
  total: number,
): QuizProgress {
  const key = quizCellKey(tier, category);
  const prevBest = progress.bestScores[key];
  const isBetter = !prevBest || correct / total > prevBest.correct / prevBest.total;
  const bestScores = {
    ...progress.bestScores,
    [key]: isBetter ? { correct, total, at: Date.now() } : prevBest,
  };
  const passed = total > 0 && correct / total >= QUIZ_PASS_THRESHOLD;
  const clearedTiers =
    category === "all" && passed && !progress.clearedTiers.includes(tier)
      ? [...progress.clearedTiers, tier]
      : progress.clearedTiers;
  return { bestScores, clearedTiers };
}

/** the highest tier cleared, i.e. the player's current rank — null if none cleared yet */
export function currentRank(progress: QuizProgress): QuizTier | null {
  for (let i = QUIZ_TIERS.length - 1; i >= 0; i--) {
    if (progress.clearedTiers.includes(QUIZ_TIERS[i])) return QUIZ_TIERS[i];
  }
  return null;
}

